def invert_two_level(r, t1, t2):
    """the two-level inversion: the larger root g of
    r g^2 + (r (t1^2+t2^2) - (t2-t1)^2) g + r t1^2 t2^2 = 0;
    returns None when no positive real root exists."""
    if r <= 0.0:
        return None
    a = r
    b = r * (t1 * t1 + t2 * t2) - (t2 - t1) ** 2
    c = r * t1 * t1 * t2 * t2
    disc = b * b - 4.0 * a * c
    if disc < 0.0:
        return None
    g = (-b + math.sqrt(disc)) / (2.0 * a)
    return g if g > 0.0 else None


