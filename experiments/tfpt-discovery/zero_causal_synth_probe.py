# ================================================== ZA constructions
def nbar(T):
    return T / (2 * np.pi) * (np.log(T / (2 * np.pi)) - 1.0) + 0.875


def za_maps(t_syn: float) -> tuple:
    tg = np.linspace(6.5, t_syn * 1.0000001, 2 ** 21)
    xg = nbar(tg)
    return tg, xg


def za_poisson(s: int, n: int, t_syn: float, tg, xg) -> np.ndarray:
    rng = np.random.default_rng([2100, s])
    xp = np.sort(rng.random(n) * nbar(t_syn))
    return np.interp(xp, xg, tg)


def wigner_cdf() -> tuple:
    sg = np.linspace(0.0, 6.0, 60001)
    pdf = (32.0 / np.pi ** 2) * sg ** 2 * np.exp(-4.0 * sg ** 2 / np.pi)
    cdf = np.concatenate([[0.0], np.cumsum(
        (pdf[1:] + pdf[:-1]) * 0.5 * np.diff(sg))])
    return sg, cdf / cdf[-1]


def za_gue(s: int, n: int, t_syn: float, tg, xg, sg, cdf) -> tuple:
    rng = np.random.default_rng([2200, s])
    sp = np.interp(rng.random(n), cdf, sg)
    xp = np.cumsum(sp)
    xp = xp * (nbar(t_syn) / xp[-1])
    var = float(np.var(sp / np.mean(sp)))
    return np.interp(xp, xg, tg), var


