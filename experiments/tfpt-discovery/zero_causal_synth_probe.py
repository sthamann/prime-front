def zsum_pj(gamv: np.ndarray, aa, K: int, delta: float = 0.0):
    """zero-side pj fluctuation sum.  delta = 0: the r175 on-line form
    4 om sin^2(A g)/(g^2 - om^2).  delta > 0: the general-rho closed
    form -2 Re[om(1 - e^{sL})/(s^2 + om^2)], s = delta + ig."""
    A = float(aa)
    out = np.zeros(K)
    if delta == 0.0:
        s2 = np.sin(A * gamv) ** 2
        g2 = gamv * gamv
        for k in range(1, K):
            om = k * math.pi / A
            out[k] = float(np.sum(4.0 * om * s2 / (g2 - om * om)))
    else:
        L = 2.0 * A
        s = delta + 1j * gamv
        eL = np.exp(s * L)
        s2 = s * s
        for k in range(1, K):
            om = k * math.pi / A
            out[k] = float(np.sum(-2.0 * np.real(
                om * (1.0 - eL) / (s2 + om * om))))
    return out


def _E1J1(s, eb_s, ea_s, a: float, b: float):
    """(Int_a^b e^{isu} du, Int_a^b u e^{isu} du) -- r175 VERBATIM;
    accepts complex s (the off-line effective ordinate)."""
    small = np.abs(s) * max(abs(a), abs(b)) <= 1e-2
    isv = 1j * s
    with np.errstate(divide="ignore", invalid="ignore"):
        E1 = (eb_s - ea_s) / isv
        J1 = eb_s * (b / isv + 1.0 / (s * s)) \
            - ea_s * (a / isv + 1.0 / (s * s))
    if np.any(small):
        sm = s[small]
        accE = np.zeros(len(sm), complex)
        accJ = np.zeros(len(sm), complex)
        for n in range(7):
            fn = math.factorial(n)
            accE += (1j * sm) ** n * (b ** (n + 1) - a ** (n + 1)) \
                / (fn * (n + 1))
            accJ += (1j * sm) ** n * (b ** (n + 2) - a ** (n + 2)) \
                / (fn * (n + 2))
        E1[small] = accE
        J1[small] = accJ
    return E1, J1


def zsum_pd(gamv: np.ndarray, aa, K: int, u0: float,
            delta: float = 0.0):
    """zero-side pd fluctuation sum -2 Re W_d (r175 VERBATIM; off-line
    via the complex effective ordinate g_eff = g - i delta)."""
    A = float(aa)
    b = 2 * A
    if delta != 0.0:
        gv = gamv - 1j * delta
    else:
        gv = gamv
    Eb = np.exp(1j * b * gv)
    Ea = np.exp(1j * u0 * gv)
    out = np.zeros(K)
    for k in range(K):
        if k == 0:
            E1, J1 = _E1J1(gv, Eb, Ea, u0, b)
            W = 2 * A * E1 - J1
        else:
            om = k * math.pi / A
            fb = complex(np.exp(1j * om * b))
            fa = complex(np.exp(1j * om * u0))
            E1p, J1p = _E1J1(gv + om, Eb * fb, Ea * fa, u0, b)
            E1m, J1m = _E1J1(gv - om, Eb / fb, Ea / fa, u0, b)
            Wc = (E1p + E1m) / 2
            Ws = (E1p - E1m) / (2j)
            Wuc = (J1p + J1m) / 2
            W = A * Wc - Wuc / 2 - Ws / (2 * om)
        out[k] = float(np.sum(-2.0 * np.real(W)))
    return out


# ==================================================== D2 weight engine
def osc_dens(gs: np.ndarray, us: np.ndarray, beta: float = 0.5,
             chunk: int = CHUNK_Z) -> np.ndarray:
    """F(u) = sum_g [2 beta cos(g u) + 2 g sin(g u)]/(beta^2 + g^2);
    OSC(x) = x^beta F(ln x).  Chunked, deterministic order."""
    F = np.zeros(len(us))
    for lo in range(0, len(gs), chunk):
        g = gs[lo: lo + chunk]
        den = beta * beta + g * g
        al = 2.0 * beta / den
        be = 2.0 * g / den
        ph = np.outer(us, g)
        F += np.cos(ph) @ al + np.sin(ph) @ be
    return F


def weights_from_dens(qs: np.ndarray, F1: np.ndarray, F2: np.ndarray,
                      beta: float = 0.5) -> tuple:
    """increment pieces: returns (osc_inc,) given densities at the
    window endpoints; combined by synth_weights."""
    x1 = qs - 0.5
    x2 = qs + 0.5
    return (x2 ** beta) * F2 - (x1 ** beta) * F1


def triv_inc(qs: np.ndarray) -> np.ndarray:
    x1 = qs - 0.5
    x2 = qs + 0.5
    return -0.5 * (np.log1p(-x2 ** -2.0) - np.log1p(-x1 ** -2.0))


def synth_weights(qs: np.ndarray, osc: np.ndarray) -> np.ndarray:
    """w = [1 - osc_inc + triv_inc]/sqrt q (the ONE frozen recipe)."""
    return (1.0 - osc + triv_inc(qs)) / np.sqrt(qs)


