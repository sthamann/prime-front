def pin_model_fractions(lam1, lam2, fa1, fa2, fb1, fb2):
    """one exact rational rank-2 pinning model: returns (p', q',
    c', margin, g21, Dt, ok) with ok = the three pinning identities
    EXACT in Fractions: (i) the dressed-2x2 deficits are (1-lam1),
    (1-lam2) (root identity: sum + product), (ii) p'q' - c'^2 ==
    m^2 g21/Dt^2, (iii) c' == m G."""
    mu1, mu2 = 1 / (1 - lam1), 1 / (1 - lam2)
    M11 = mu1 * fa1 * fa1 + mu2 * fb1 * fb1
    M22 = mu1 * fa2 * fa2 + mu2 * fb2 * fb2
    M12 = mu1 * fa1 * fa2 + mu2 * fb1 * fb2
    detM = M11 * M22 - M12 * M12
    pp, qq, cc = M22 / detM, M11 / detM, M12 / detM
    m = 1 - lam1
    g21 = (1 - lam2) / (1 - lam1)
    Dt = fa1 * fb2 - fa2 * fb1
    ok_roots = (pp + qq == (1 - lam1) + (1 - lam2)
                and pp * qq - cc * cc == (1 - lam1) * (1 - lam2))
    ok_det = (pp * qq - cc * cc == m * m * g21 / (Dt * Dt))
    G = (g21 * fa1 * fa2 + fb1 * fb2) / (Dt * Dt)
    ok_geom = (cc == m * G)
    return pp, qq, cc, m, g21, Dt, (ok_roots and ok_det
                                    and ok_geom)


