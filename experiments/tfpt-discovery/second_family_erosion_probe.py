def frameb_select(fresh, zvals, grels, z_lo, z_hi, k_bz):
    """the sealed frame-B two-strata queue rule: stratum BZ =
    fresh kz with z in [z_lo, z_hi] sorted by (grel, kz)
    ascending; stratum BD = the remaining fresh sorted by (h, kz)
    DESCENDING.  Returns the two CANDIDATE QUEUES (admission by
    the caller: POSITIVE_PREFIX + chain-complete, failing
    candidates replaced by the next in queue).  Consumes window
    shape + grid columns only."""
    fresh_kz = [kz for (_h, kz) in fresh]
    zb = {kz: zvals[i] for i, kz in enumerate(fresh_kz)}
    gb = {kz: grels[i] for i, kz in enumerate(fresh_kz)}
    b_q = sorted((kz for kz in fresh_kz
                  if z_lo <= zb[kz] <= z_hi),
                 key=lambda kz: (gb[kz], kz))
    b_set = set(b_q[:k_bz])
    d_q = [kz for (_h, kz) in sorted(fresh, reverse=True)
           if kz not in b_set]
    return b_q, d_q


