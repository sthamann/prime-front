        u0m = mp.mpf(repr(u0))
        out = []
        for k in range(K):
            if k == 0:
                fd = lambda u: L - u                        # noqa: E731
                pts = [u0m, L]
            else:
                o = k * mp.pi / aa
                fd = lambda u, o=o: ((aa - u / 2) * mp.cos(o * u)   # noqa: E731
                                     - mp.sin(o * u) / (2 * o))
                npts = max(int(mp.floor(L * o / mp.pi)), 1)
                pts = sorted(set(
                    [u0m, L] + [jj * mp.pi / o
                                for jj in range(1, npts + 1)
                                if jj * mp.pi / o > u0m]))
            out.append(float(mp.quad(
                lambda u, fd=fd: fd(u) * mp.exp(-u / 2)
                / mp.expm1(2 * u), pts)))
        return out


