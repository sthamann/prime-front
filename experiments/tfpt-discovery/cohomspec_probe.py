def fraction_det(matrix: list[list[Fraction]]) -> Fraction:
    n = len(matrix)
    work = [row[:] for row in matrix]
    det = Fraction(1)
    for col in range(n):
        pivot_row = next((r for r in range(col, n) if work[r][col] != 0), None)
        if pivot_row is None:
            return Fraction(0)
        if pivot_row != col:
            work[col], work[pivot_row] = work[pivot_row], work[col]
            det = -det
        det *= work[col][col]
        inv = Fraction(1) / work[col][col]
        for r in range(col + 1, n):
            factor = work[r][col] * inv
            if factor:
                work[r] = [a - factor * b
                           for a, b in zip(work[r], work[col])]
    return det


def fraction_solve(matrix: list[list[Fraction]],
                   rhs: list[Fraction]) -> list[Fraction]:
    n = len(matrix)
    work = [matrix[r][:] + [rhs[r]] for r in range(n)]
    for col in range(n):
        pivot_row = next(r for r in range(col, n) if work[r][col] != 0)
        work[col], work[pivot_row] = work[pivot_row], work[col]
        inv = Fraction(1) / work[col][col]
        work[col] = [value * inv for value in work[col]]
        for r in range(n):
            if r != col and work[r][col]:
                factor = work[r][col]
                work[r] = [a - factor * b
                           for a, b in zip(work[r], work[col])]
    return [work[r][n] for r in range(n)]


def leading_minors(matrix: list[list[Fraction]]) -> list[Fraction]:
    return [fraction_det([row[:k] for row in matrix[:k]])
            for k in range(1, len(matrix) + 1)]


