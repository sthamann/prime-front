def frac_rng_mat(rng, n):
    def rfr():
        return Fraction(int(rng.integers(-9, 10)), int(rng.integers(1, 8)))
    return [[rfr() for _ in range(n)] for _ in range(n)], rfr


def frac_det(mat):
    n = len(mat)
    m = [row[:] for row in mat]
    det = Fraction(1)
    for col in range(n):
        piv = next((r for r in range(col, n) if m[r][col] != 0), None)
        if piv is None:
            return Fraction(0)
        if piv != col:
            m[col], m[piv] = m[piv], m[col]
            det = -det
        det *= m[col][col]
        inv = Fraction(1) / m[col][col]
        m[col] = [x * inv for x in m[col]]
        for r in range(col + 1, n):
            if m[r][col] != 0:
                f = m[r][col]
                m[r] = [x - f * y for x, y in zip(m[r], m[col])]
    return det


def frac_solve_sym(mat, rhs):
    n = len(mat)
    m = [row[:] + [rhs[i]] for i, row in enumerate(mat)]
    for col in range(n):
        piv = next(r for r in range(col, n) if m[r][col] != 0)
        m[col], m[piv] = m[piv], m[col]
        pv = m[col][col]
        m[col] = [x / pv for x in m[col]]
        for r in range(n):
            if r != col and m[r][col] != 0:
                f = m[r][col]
                m[r] = [x - f * y for x, y in zip(m[r], m[col])]
    return [m[r][n] for r in range(n)]


def bordered_pack(seed):
    """(a) soft existence, (b) PD(M) <=> s > 0 via det M = s det B,
    (c) ellipsoid membership margin == s.  Exact Fractions."""
    rng = np.random.default_rng(seed)
    hm = 6
    mrand, rfr = frac_rng_mat(rng, hm)
    bmat = [[sum(mrand[k][i] * mrand[k][j] for k in range(hm))
             + (Fraction(1) if i == j else Fraction(0))
             for j in range(hm)] for i in range(hm)]
    b = [rfr() for _ in range(hm)]
    x = frac_solve_sym(bmat, b)
    q = sum(bi * xi for bi, xi in zip(b, x))
    det_b = frac_det(bmat)
    ok = det_b > 0

    def bordered(nv, bv):
        top = [nv] + list(bv)
        rows = [top]
        for i in range(hm):
            rows.append([bv[i]] + list(bmat[i]))
        return rows

    def lead_minors_pos(mat):
        return all(frac_det([row[:k] for row in mat[:k]]) > 0
                   for k in range(1, len(mat) + 1))

    # (a) soft existence: border 0 completion PD for ANY n > 0
    ok &= lead_minors_pos(bordered(Fraction(1, 100),
                                   [Fraction(0)] * hm))
    # (b) det M = s det B, PD <=> s > 0, both sides
    for n_val, want_pd in ((q + Fraction(1, 3), True),
                           (q - Fraction(1, 3), False)):
        s_val = n_val - q
        m_full = bordered(n_val, b)
        ok &= (frac_det(m_full) == s_val * det_b)
        ok &= (lead_minors_pos(m_full) == want_pd)
        # (c) Krein admissible set {b : q(b) <= n}: membership margin
        ok &= (n_val - q == s_val)
    return ok


def toeplitz_pack(seed):
    """Caratheodory-Toeplitz one-step extension, exact Fractions:
    interval nonempty (soft), arithmetic value admissible with margin
    exactly the next Schur scalar."""
    rng = np.random.default_rng(seed)
    xlen, k = 12, 7
    xseq = [Fraction(int(rng.integers(-5, 6)), int(rng.integers(1, 6)))
            for _ in range(xlen)]
    c = [sum(xseq[j] * xseq[j + d] for j in range(xlen - d))
         for d in range(k + 1)]

    def toep(vals, n):
        return [[vals[abs(i - j)] for j in range(n)] for i in range(n)]

    m7 = toep(c, k)
    ok = all(frac_det([row[:j] for row in m7[:j]]) > 0
             for j in range(1, k + 1))
    det7 = frac_det(m7)

    def det8(corner):
        vals = c[:k] + [corner]
        return frac_det(toep(vals, k + 1))

    # det8 is an exact quadratic in the corner: Lagrange at 0, 1, 2
    d0, d1, d2 = det8(Fraction(0)), det8(Fraction(1)), det8(Fraction(2))
    a_q = (d2 - 2 * d1 + d0) / 2
    b_q = d1 - d0 - a_q
    c_q = d0
    ok &= (a_q < 0)                              # concave: an interval
    vertex = -b_q / (2 * a_q)
    ok &= (a_q * vertex ** 2 + b_q * vertex + c_q > 0)   # soft existence
    c_true = c[k]
    val_true = a_q * c_true ** 2 + b_q * c_true + c_q
    ok &= (val_true == det8(c_true))
    ok &= (val_true >= 0)                        # arithmetic admissible
    # margin == next Schur scalar: s8 * det M7 == det M8(c_true)
    m8 = toep(c[:k] + [c_true], k + 1)
    col = [m8[i][k] for i in range(k)]
    y = frac_solve_sym(m7, col)
    s8 = m8[k][k] - sum(ci * yi for ci, yi in zip(col, y))
    ok &= (s8 * det7 == val_true)
    return ok


def wall_row_light(wall, theta, a2mat):
    """SAT-round float64 row at one (cell, theta): same generators as
    the deployed pipeline, mid values only (X4 consumed, typed).  Used
    at the deep cells where f4's certified tier refuses (CERT-WEAK)."""
    h = wall.h
    car, cat = wall.c_ladder(theta, split=True)
    xs_int = np.arange(-1.0, h + 2.0)
    ci = wall.c_scalar_vec(xs_int)
    ci_ar = sap.core.arch_A(np.abs(xs_int) * wall.D, wall.D)
    c_tot = car + cat
    gh = c_tot[1:-1] - 0.5 * (c_tot[2:] + c_tot[:-2])
    gh_ar = car[1:-1] - 0.5 * (car[2:] + car[:-2])
    om = wall.omega_from_gh(gh)
    gt_ar = ci_ar[1:h + 1] - 0.5 * (ci_ar[2:h + 2] + ci_ar[0:h])
    om0 = 0.5 * (sla.hankel(gh_ar[:h], gh_ar[h - 1:2 * h - 1])
                 + sla.toeplitz(gt_ar[:h]))
    n_true = float(om[0, 0])
    n0 = float(om0[0, 0])
    b = np.ascontiguousarray(om[1:, 0])
    bmat = np.ascontiguousarray(om[1:, 1:])
    b0 = np.ascontiguousarray(om0[1:, 0])
    bc = b0 - b
    nc = n0 - n_true
    w = -(cat[:h + 2] + (ci - ci_ar)[:h + 2])
    fact_resid = float(np.max(np.abs(-0.25 * (a2mat @ w) - bc)))
    try:
        cf = sla.cho_factor(bmat, lower=True, check_finite=False)
    except np.linalg.LinAlgError:
        return dict(theta=theta, refused="CHOL-FAIL")
    x0 = sla.cho_solve(cf, b0, check_finite=False)
    yb = sla.cho_solve(cf, b, check_finite=False)
    zc = sla.cho_solve(cf, bc, check_finite=False)
    q0 = fsum(b0 * x0)
    q = fsum(b * yb)
    qc = fsum(bc * zc)
    v = msc.second_difference_T(x0, h)
    s_val = n_true - q
    return dict(theta=theta, refused=None, n_true=n_true, n0=n0,
                nc=nc, w_min=float(np.min(w)), fact_resid=fact_resid,
                q0_hi=q0, q0_lo=q0, qc_hi=qc, qc_lo=qc,
                s_lo=s_val, s_hi=s_val,
                signed=-0.5 * fsum(w * v), v_vec=v)


