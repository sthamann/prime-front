# ============================== exact tent-expansion family machinery
def b3_spline(t):
    """Cubic cardinal B-spline: b3(0)=2/3, b3(+-1)=1/6, supp (-2,2)."""
    a = np.abs(np.asarray(t, float))
    return np.where(a < 1.0, 2.0 / 3.0 - a * a + 0.5 * a ** 3,
                    np.where(a < 2.0, (2.0 - a) ** 3 / 6.0, 0.0))


class SquareFamily:
    """g even, compactly supported, cellwise-affine on m uniform cells
    of [0, Sg]; g(Sg) = 0.  Exact tent expansion c_j = g(j dg); exact
    f = g * g~ = dg sum_d a_d B3(x/dg - d) (a_d the exact discrete
    autocorrelation); ghat(xi) = dg sinc^2(xi dg/2) C(xi) closed form,
    fhat = ghat^2 >= 0 structurally."""

    def __init__(self, name, gv, sg):
        gv = np.asarray(gv, float).copy()
        gv[-1] = 0.0
        self.name, self.gv, self.sg = name, gv, float(sg)
        self.m = len(gv) - 1
        self.dg = self.sg / self.m
        cfull = np.concatenate([gv[::-1], gv[1:]])       # c_{-m}..c_m
        acorr = np.convolve(cfull, cfull)                # symmetric
        self.a_lag = acorr[2 * self.m:]                  # a_0..a_{2m}
        self.support = 2.0 * self.sg                     # f support
        # ||g||_2^2 by exact per-cell Simpson (quadratic integrand)
        aa, bb = gv[:-1], gv[1:]
        self.norm2 = 2.0 * fsum(self.dg * (aa * aa + aa * bb + bb * bb)
                                / 3.0)

    def f_eval(self, u):
        """EXACT f = g * g~ at u >= 0 (vectorized, 4 B-spline terms)."""
        t = np.asarray(u, float) / self.dg
        out = np.zeros_like(t)
        base = np.floor(t).astype(np.int64) - 1
        for off in range(4):
            d = base + off
            ad = np.where(np.abs(d) <= 2 * self.m,
                          self.a_lag[np.minimum(np.abs(d), 2 * self.m)],
                          0.0)
            out += ad * b3_spline(t - d)
        return self.dg * out

    def ghat(self, xis):
        """Closed-form ghat on real xi (full Fourier transform)."""
        xis = np.asarray(xis, float)
        y = 0.5 * xis * self.dg
        sinc = np.where(np.abs(y) < 1e-12, 1.0, np.sin(y) / y)
        jv = np.arange(1, self.m + 1, dtype=float)
        cosm = np.cos(np.outer(xis, jv * self.dg))
        cval = self.gv[0] + 2.0 * (cosm @ self.gv[1:self.m + 1])
        return self.dg * sinc * sinc * cval

    def ghat_c(self, z):
        """Complex continuation of ghat at one complex z."""
        y = 0.5 * z * self.dg
        sinc = 1.0 + 0j if abs(y) < 1e-12 else np.sin(y) / y
        tot = self.gv[0] + 0j
        for j in range(1, self.m + 1):
            tot += 2.0 * self.gv[j] * np.cos(j * z * self.dg)
        return self.dg * sinc * sinc * tot

    def zero_q(self, gammas, chunk=125_000):
        """Q = 2 sum_{gamma>0} ghat(gamma)^2 (conjugate pairs)."""
        tot = 0.0
        for i in range(0, len(gammas), chunk):
            gh = self.ghat(gammas[i:i + chunk])
            tot += float(np.sum(gh * gh))
        return 2.0 * tot

    def tail_bound(self, t_top):
        """Outward tail bound for 2 sum_{gamma>T} ghat^2 via
        |ghat| <= 4 C_max / (xi^2 dg) and dN <= (log(t/2pi)+1)/pi dt."""
        c_max = float(self.gv[0] + 2.0 * np.sum(np.abs(self.gv[1:])))
        amp = (4.0 * c_max / self.dg) ** 2
        lg = math.log(t_top / (2.0 * math.pi)) + 1.0
        return 2.0 * amp * lg / (math.pi * 3.0 * t_top ** 3)


def gl_int(fn, a_edges, glx, glw):
    a = a_edges[:-1]
    b = a_edges[1:]
    half = 0.5 * (b - a)
    mid = 0.5 * (a + b)
    xs = mid[:, None] + half[:, None] * glx[None, :]
    vals = fn(xs.ravel()).reshape(xs.shape)
    return float(np.sum(half[:, None] * glw[None, :] * vals))


def source_side(fam_or_callable, f0, s_end, dg_hint, glx, glw):
    """POLE = 4 int f cosh(x/2), P_main = 2 int f e^{x/2},
    BSUP = 2 int f e^{-x/2}, ARCH via the deployed integrand; all on
    panels aligned to the profile grid + geometric refinement at 0."""
    fe = fam_or_callable
    n_cell = max(8, int(math.ceil(s_end / dg_hint)))
    base = np.linspace(0.0, s_end, n_cell + 1)
    geo = s_end * 0.5 ** np.arange(46, 0, -1)
    edges = np.unique(np.concatenate([base, geo]))
    pole = 4.0 * gl_int(lambda x: fe(x) * np.cosh(0.5 * x), edges,
                        glx, glw)
    pmain = 2.0 * gl_int(lambda x: fe(x) * np.exp(0.5 * x), edges,
                         glx, glw)
    bsup = 2.0 * gl_int(lambda x: fe(x) * np.exp(-0.5 * x), edges,
                        glx, glw)

    def ib(w):
        return ((f0 * np.exp(-2.0 * w) - fe(w) * np.exp(-0.5 * w))
                / (-np.expm1(-2.0 * w)))
    body = gl_int(ib, edges, glx, glw)
    tail = -0.5 * f0 * math.log1p(-math.exp(-2.0 * s_end))
    arch = -f0 * (EULER + math.log(math.pi)) + 2.0 * (body + tail)
    return dict(pole=pole, pmain=pmain, arch=arch, bsup=bsup,
                bar=bsup + arch)


