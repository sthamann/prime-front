def ols_slope(xs, ys):
    """Closed-form OLS slope (no fitting call)."""
    n = len(xs)
    mx = sum(xs) / n
    my = sum(ys) / n
    sxx = sum((x - mx) ** 2 for x in xs)
    sxy = sum((x - mx) * (y - my) for x, y in zip(xs, ys))
    return sxy / sxx if sxx > 0 else float("nan")


def ols_fit(xs, ys):
    sl = ols_slope(xs, ys)
    n = len(xs)
    icpt = sum(ys) / n - sl * sum(xs) / n
    return sl, icpt


