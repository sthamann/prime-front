    h = m_z // 2
    d_val = alpha / h
    s_len = 2.0 * alpha * (1.0 + 1.0 / h)
    return dict(kz=kz, alpha=alpha, D=d_val, h=h, S=s_len,
                N=math.floor(math.exp(s_len)))


