def q_parts(atoms):
    """(pole, prime, arch, Q) for a shifted-Gaussian atom list —
    route A: closed-form pole and ĥ, exact prime evaluation,
    digamma-kernel quadrature for the arch term."""
    pole = sum(a * s * SQ2PI * math.exp(s * s / 8.0)
               * (math.exp(c / 2.0) + math.exp(-c / 2.0))
               for a, c, s in atoms)
    hp = h_eval(atoms, PP_U) + h_eval(atoms, -PP_U)
    prime = float(np.dot(PP_W, hp))
    reh = np.zeros_like(T_GRID)
    for a, c, s in atoms:
        reh += (a * s * SQ2PI * np.exp(-0.5 * (s * T_GRID) ** 2)
                * np.cos(c * T_GRID))
    arch = float(np.trapezoid(reh * K_T, T_GRID)) / math.pi
    return pole, prime, arch, pole - prime + arch


