    rt = float(np.sqrt(np.mean(t ** 2)))
    share = float(np.sqrt(np.mean(x ** 2))) / max(rt, 1e-300)
    lo = float(np.sqrt(np.mean((t - x) ** 2))) / max(rt, 1e-300)
    return corr, share, lo


