def y0_reduced(B, i1, i2, c):
    """the EXACT reduced route of the delta_0 column: y0 = 1 +
    (u1 . u2)/c with u_k = E[i_k, rest] (T0 = sum alpha beta =
    u1 . u2 by orthogonality of the rest eigenbasis); consumes
    the dressed frame only -- no eigendecomposition, no
    resolvent."""
