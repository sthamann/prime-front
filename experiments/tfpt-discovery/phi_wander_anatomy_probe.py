def cd_blocks(xp, wp, yn, i1, i2, Nw):
    """the CD source blocks at the pair: the mu-chain recomputed
    from the measure (document route), then b_{N-1}, the CD
    polynomial factor P12 = p_N(y1) p_{N-1}(y2) - p_{N-1}(y1)
    p_N(y2), the pair gap dy = y1 - y2, and the kernel values
    K11/K22/K12 via the endpoint/confluent formulas (r350
    verbatim recursion); consumes measure arrays + positions
    only."""
    aa, bb, h0 = V.mu_chain(xp, wp, Nw)
    y1 = float(yn[i1])
    y2 = float(yn[i2])

    def pvals(y):
        p = np.zeros(Nw + 1)
        dp = np.zeros(Nw + 1)
        p[0] = 1.0 / math.sqrt(h0)
        pm, dm = 0.0, 0.0
        for i in range(Nw):
            pn = ((y - aa[i]) * p[i]
                  - (bb[i - 1] * pm if i > 0 else 0.0)) / bb[i]
            dn = (p[i] + (y - aa[i]) * dp[i]
                  - (bb[i - 1] * dm if i > 0 else 0.0)) / bb[i]
            pm, dm = p[i], dp[i]
            p[i + 1], dp[i + 1] = pn, dn
        return p, dp

    p1, d1v = pvals(y1)
    p2, d2v = pvals(y2)
    bN = float(bb[Nw - 1])
    P12 = float(p1[Nw] * p2[Nw - 1] - p1[Nw - 1] * p2[Nw])
    dy = y1 - y2
    K12 = bN * P12 / dy
    K11 = bN * float(d1v[Nw] * p1[Nw - 1] - d1v[Nw - 1] * p1[Nw])
    K22 = bN * float(d2v[Nw] * p2[Nw - 1] - d2v[Nw - 1] * p2[Nw])
    return bN, P12, dy, K11, K22, K12


