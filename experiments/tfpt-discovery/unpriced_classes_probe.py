def phi_scat(s):
    """Modular-surface scattering matrix
    phi(s) = sqrt(pi) Gamma(s - 1/2) zeta(2s - 1) / (Gamma(s) zeta(2s))."""
    return (mp.sqrt(mp.pi) * mp.gamma(s - mp.mpf(1) / 2)
            * mp.zeta(2 * s - 1) / (mp.gamma(s) * mp.zeta(2 * s)))


def e_contour(y):
    """e(y) = (1/2 pi i) int_(1/2) Gamma(2-s)(y^s + phi(s) y^{1-s}) ds,
    folded to t >= 0 by the reality of the integrand's real part."""
    ymp = mp.mpf(y)

    def integrand(t):
        s = mp.mpf(1) / 2 + 1j * t
        return mp.re(mp.gamma(2 - s)
                     * (ymp ** s + phi_scat(s) * ymp ** (1 - s)))

    return float(mp.quad(integrand, UA_QUAD_PTS) / mp.pi)


def totient_sieve(cap):
    phi = np.arange(cap + 1, dtype=np.int64)
    for p in range(2, cap + 1):
        if phi[p] == p:                                  # p prime
            phi[p::p] -= phi[p::p] // p
    return phi


def h_direct(y, C=UA_C_TRUNC, nodes=UA_GL_NODES):
    """Coset-unfolded horocycle integral of the incomplete Eisenstein
    series with psi(t) = t^2 e^{-t}:
      H(y) = psi(y) + sum_{c>=1} phi_E(c) (c^4 y)^{-1}
             int_{-pi/2}^{pi/2} cos^2 th exp(-cos^2 th/(c^2 y)) dth.
    Returns (value, truncation envelope pi/(4 y C^2))."""
    x, w = np.polynomial.legendre.leggauss(nodes)
    th = 0.5 * (x + 1.0) * (math.pi / 2.0)              # [0, pi/2]
    ww = w * (math.pi / 4.0)
    c = np.arange(1, C + 1, dtype=float)
    phiE = totient_sieve(C)[1:].astype(float)
    cos2 = np.cos(th) ** 2
    ex = np.exp(-np.outer(1.0 / (c * c * y), cos2))
    integ = 2.0 * (ex * cos2[None, :]) @ ww             # even integrand
    terms = phiE / (c ** 4 * y) * integ
    tail = math.pi / (4.0 * y * C * C)
    return float(y * y * math.exp(-y) + terms.sum()), tail


