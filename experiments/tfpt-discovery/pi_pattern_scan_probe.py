    check("G20-champ-fires", min(st_champ_w) >= CTRL_FIRE_RATIO * nw,
          "Champernowne Weyl stat %.1f/%.1f >= 3 x null max %.2f "
          "(structured control fires)"
          % (st_champ_w[0], st_champ_w[1], nw))
    check("G21-phi-gk-fires", st_phi_gk >= CTRL_FIRE_RATIO * ng,
          "phi CF GK chi2 = %.1f >= 3 x null max %.2f (all-1s CF "
          "maximally non-GK)" % (st_phi_gk, ng))
    info("e CF GK chi2 = %.1f (semi-structured control, measured)"
         % st_e_gk)

    pi_anom_d3 = []
    for leg, (va, vb, nmax) in (
            ("WEYL10", (st_pi["weylA"], st_pi["weylB"], nw)),
            ("BITS2", (st_pi["bitA"], st_pi["bitB"], nbt)),
            ("GK-CHI2", (st_pi["gkA"], st_pi["gkB"], ng))):
        fa, fb = va > ANOM_RATIO * nmax, vb > ANOM_RATIO * nmax
        verdict = ("ANOMALY-REPLICATES" if fa and fb else
                   "NON-REPLICATING" if fa else "null")
        if fa and fb:
            pi_anom_d3.append((leg, va, vb))
        print("  pi %-8s A %.2f  B %.2f  null max %.2f  %s"
              % (leg, va, vb, nmax, verdict))
    check("G22-d3-adjudication", True,
          "DEFINITIONAL/ADJUDICATION: pi D3 flags = %s"
          % (pi_anom_d3 if pi_anom_d3 else "NONE"))

    # ------------------------------------------------------------ S5
    section("S5  D4 OCCUPANCY / CLASSICAL LAWS")
    at = mangoldt_atoms_f(PSI_X)
    psi = sum(w * math.sqrt(math.exp(u)) for u, w in at)
    # NOTE w = log p/sqrt q -> Lambda(q) = w sqrt q; psi = sum Lambda
    ratio = psi / PSI_X
    check("G23-psi-x", PSI_BAND[0] <= ratio <= PSI_BAND[1],
          "psi(%d)/%d = %.5f in [0.97, 1.03] (Chebyshev/"
          "Rosser-Schoenfeld class)" % (PSI_X, PSI_X, ratio))
    occ_ok = True
    occs = []
    for j in DYADIC_J:
        cnt = sum(1 for u, _w in at
                  if 2 ** j <= math.exp(u) < 2 ** (j + 1)
                  and 2 ** j <= PSI_X)
        prednum = 2 ** j / (j * math.log(2))
        occs.append(cnt / prednum)
        occ_ok = occ_ok and DYADIC_BAND[0] <= cnt / prednum \
            <= DYADIC_BAND[1]
    check("G24-mangoldt-occupancy", occ_ok,
          "dyadic prime-power occupancy / (2^j/(j ln 2)) = %s in "
          "[0.75, 1.25] (PNT block law)"
          % ["%.3f" % v for v in occs])

    lq_pi = cf_logq(CFS["pi"][:ncf_depth])
    gaps_pi = np.diff(np.array([0.0] + lq_pi))
    dev_levy = abs(float(gaps_pi.mean()) - LEVY)
    null_levy = []
    for s in range(nseed):
        lqr = cf_logq(gen_cf_rand(s, ncf_depth))
        null_levy.append(abs(float(np.diff(np.array([0.0] + lqr))
                                   .mean()) - LEVY))
    lq_phi = cf_logq(CFS["phi"][:ncf_depth])
    gap_phi = float(np.diff(np.array([0.0] + lq_phi)).mean())
    sig = float(np.std(null_levy)) or 1e-12
    check("G25-levy-pi", dev_levy <= LEVY_TOL,
          "pi CF-geom mean gap dev from Levy %.6f = %.4f <= %.4f "
          "(null max %.4f; Levy 1936)"
          % (LEVY, dev_levy, LEVY_TOL, max(null_levy)))
    check("G26-levy-phi-separates",
          abs(gap_phi - LEVY) / sig >= PHI_SEP_SIGMA,
          "phi mean gap %.4f (= ln phi) vs Levy: %.0f sigma of null "
          "spread -- the law detector separates structure"
          % (gap_phi, abs(gap_phi - LEVY) / sig))
    gm_pi = float(np.exp(np.mean(np.log(
        np.array(CFS["pi"][:ncf_depth], dtype=float)))))
    null_kh = []
    for s in range(nseed):
        ar = np.array(gen_cf_rand(s, ncf_depth), dtype=float)
        null_kh.append(abs(float(np.exp(np.mean(np.log(ar)))) - K0))
    check("G27-khinchin-pi", abs(gm_pi - K0) <= KH_TOL,
          "pi CF GM = %.4f vs K0 %.4f (dev %.4f <= %.4f; null max "
          "%.4f; Khinchin 1934)"
          % (gm_pi, K0, abs(gm_pi - K0), KH_TOL, max(null_kh)))
    check("G28-gk-pi", st_pi["gkA"] + st_pi["gkB"] <= 2 * GK_BAR,
          "pi GK chi2 halves %.1f/%.1f <= bar %.1f each-avg "
          "(Gauss-Kuzmin)" % (st_pi["gkA"], st_pi["gkB"], GK_BAR))
    pi_anom_d4 = []
    if dev_levy > LEVY_TOL:
        pi_anom_d4.append(("LEVY", dev_levy))
    if abs(gm_pi - K0) > KH_TOL:
        pi_anom_d4.append(("KHINCHIN", gm_pi))
    check("G29-d4-adjudication", True,
          "DEFINITIONAL/ADJUDICATION: pi D4 flags = %s"
          % (pi_anom_d4 if pi_anom_d4 else
             "NONE (pi consistent with GK/Levy/Khinchin)"))

    # ------------------------------------------------------------ S6
    section("S6  D5 ALT-JET DISSECTION (r182 recipes verbatim)")
    # frozen selection of the best-scoring pi world at h = top rung
    htop = rungs[-1]
    key_map = {"P-BBP": "P-BBP", "P-CF": "CF:pi",
               "P-DIG10": "DIG10:pi", "P-DIG2": "DIG2:pi",
               "P-CFGEOM": "CFGEOM:pi"}
    best_pi = max(
        BEST_PI_PRIORITY,
        key=lambda w: (D1[(key_map[w], "A", htop)]["log10tail"],
                       -BEST_PI_PRIORITY.index(w)))
    info("best-scoring pi world at h=%d (frozen rule): %s "
         "(log10tail %.2f)"
         % (htop, best_pi,
            D1[(key_map[best_pi], "A", htop)]["log10tail"]))
    alt_ok_mang = True
    for h in (r for r in ALT_RUNGS if r in rungs):
        for wname, lbl in ((("MANGOLDT"), "MANGOLDT"),
                           ((key_map[best_pi]), best_pi)):
            cn_str, jn_str, sh = JETS[(wname, "A", h)]
            alts = alt_jet_tails(sh, cn_str, jn_str)
            base = D1[(wname, "A", h)]["log10tail"]
            print("  h=%d %-10s MAIN %7.2f | %s"
                  % (h, lbl, base,
                     "  ".join("%s %7.2f" % (t, alts[t])
                               for t in ALT_TAGS)))
            if wname == "MANGOLDT" and h == max(
                    r for r in ALT_RUNGS if r in rungs):
                alt_ok_mang = all(alts[t] <= ALT_FAKE_BAR
                                  for t in ALT_TAGS)
                if not smoke and h == 8:
                    alt_ok_mang = (alt_ok_mang
                                   and base >= TAILRIDE_HI8)
    check("G30-mangoldt-altjets", alt_ok_mang,
          "MANGOLDT alt-jets all relocate to top (<= -8) while MAIN "
          "rides the tail: ALT-JETS-BREAK-ALIGNMENT replicated"
          + (" [SMOKE-SCOPED]" if smoke else ""))
    check("G31-d5-adjudication", True,
          "DEFINITIONAL/ADJUDICATION: best pi world %s alt-jet "
          "response reported with numbers above (no structure to "
          "kill if D1 class is TOP-HEAVY)" % best_pi)

    # ------------------------------------------------------------ S7
    section("S7  TAXONOMY VERDICT (frozen adjudication)")
    transfer_valid = (mang_cls == "TAIL-RIDING" and anchor_ok
                      and c_mang >= MANG_FIRE_RATIO
                      * max(nb["INTRAND"], nb["DIG10"])
                      and PSI_BAND[0] <= ratio <= PSI_BAND[1])
    anomalies = ([("D1",) + a for a in pi_anom_d1
                  if a[1] != "NON-REPLICATING"]
                 + [("D2",) + a for a in pi_anom_d2]
                 + [("D3", a[0]) for a in pi_anom_d3]
                 + [("D4", a[0]) for a in pi_anom_d4])
    all_fake = (all(c == "TOP-HEAVY" for c in pi_d1.values())
                and not anomalies)
    if not transfer_valid:
        taxonomy = "TRANSFER-INSTRUMENT-DEAD"
    elif all_fake:
        taxonomy = "PI-LANDS-FAKE-CLASS"
    elif anomalies:
        taxonomy = "PI-ANOMALY-AT-" + "+".join(
            sorted(set(a[0] for a in anomalies)))
    else:
        taxonomy = "MIXED"
    check("G32-taxonomy", True,
          "DEFINITIONAL/ADJUDICATION: %s (transfer_valid=%s, "
          "anomalies=%s)" % (taxonomy, transfer_valid,
                             anomalies if anomalies else "NONE"))

    # ------------------------------------------------------------ S8
    section("S8  BOOKKEEPING")
    rt = time.time() - T0_WALL
    check("G33-runtime", rt <= RUNTIME_BAR,
          "runtime %.1f s <= %.0f s" % (rt, RUNTIME_BAR))
    npass = sum(1 for _n, ok, _d in CHECKS if ok)
    ntot = len(CHECKS)
    verdict = []
    if transfer_valid:
        verdict.append("TRANSFER-VALID-MANGOLDT-FIRES")
    verdict.append(taxonomy)
    if not pi_anom_d4:
        verdict += ["CF-STATS-MATCH-GAUSS-KUZMIN",
                    "LEVY-CONSTANT-REPLICATED",
                    "KHINCHIN-GM-CONSISTENT"]
    if not pi_anom_d2:
        verdict.append("NO-SPIKE-COHERENCE")
    verdict.append("STRUCTURED-CONTROLS-FIRE-DETECTORS")
    if not pi_anom_d1:
        verdict.append("ALT-JETS-CONFIRM-NO-STRUCTURE")
    verdict += ["NO-RH-CLAIM", "NO-PI-NUMEROLOGY-CLAIM"]
    print("\n" + "=" * 78)
    print("GATES: %d/%d PASS" % (npass, ntot))
    print("COMPOSITE VERDICT: " + " + ".join(verdict))
    print("SPEC_SHA %s" % SPEC_SHA[:16])
    print("RUNTIME %.1f s" % rt)
    print("=" * 78)
    return 0 if npass == ntot else 1


