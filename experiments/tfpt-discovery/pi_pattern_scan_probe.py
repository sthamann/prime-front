def weyl_stat(digits: np.ndarray, base: int) -> float:
    n = len(digits)
    best = 0.0
    for m in range(1, WEYL_MMAX + 1):
        ph = np.exp(2j * math.pi * m * digits / base)
        best = max(best, abs(ph.mean()) * math.sqrt(n))
    return best


def bit_stat(bits: np.ndarray) -> float:
    s = 2.0 * bits.astype(float) - 1.0
    n = len(s)
    best = abs(s.sum()) / math.sqrt(n)
    for l in range(1, LAG_MAX + 1):
        best = max(best, abs(float(np.dot(s[:-l], s[l:])))
                   / math.sqrt(n - l))
    return best


def gk_chi2(quots: list) -> float:
    obs = np.zeros(GK_BINS)
    for a in quots:
        obs[min(a, GK_BINS) - 1] += 1
    n = len(quots)
    exp = np.zeros(GK_BINS)
    for j in range(1, GK_BINS):
        exp[j - 1] = n * math.log2(1 + 1.0 / (j * (j + 2)))
    exp[GK_BINS - 1] = n - exp[: GK_BINS - 1].sum()
    return float(((obs - exp) ** 2 / exp).sum())


