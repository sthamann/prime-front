def gen_digits(tag: str, n: int) -> np.ndarray:
    """first n decimal digits after the point of pi/e/sqrt2/phi,
    via mpmath at dps n + 10 (deterministic)."""
    with mp.workdps(n + 10):
        x = {"pi": mp.pi, "e": mp.e, "sqrt2": mp.sqrt(2),
             "phi": (1 + mp.sqrt(5)) / 2}[tag]
        fr = x - int(x)
        s = mp.nstr(fr, n + 5, strip_zeros=False)
    ds = s.split(".")[1][:n]
    assert len(ds) == n, (tag, len(ds))
    return np.array([int(c) for c in ds], dtype=np.int64)


def gen_bits(tag: str, n: int) -> np.ndarray:
    """first n binary digits after the point (deterministic)."""
    with mp.workdps(2 * n):
        mp.mp.prec = max(mp.mp.prec, n + 64)
        x = {"pi": mp.pi, "e": mp.e, "sqrt2": mp.sqrt(2),
             "phi": (1 + mp.sqrt(5)) / 2}[tag]
        fr = x - int(x)
        big = int(mp.floor(fr * mp.mpf(2) ** n))
    bs = bin(big)[2:].rjust(n, "0")[:n]
    return np.array([int(c) for c in bs], dtype=np.int64)


def gen_champ_digits(n: int) -> np.ndarray:
    out = []
    k = 1
    while len(out) < n:
        out.extend(int(c) for c in str(k))
        k += 1
    return np.array(out[:n], dtype=np.int64)


def gen_champ_bits(n: int) -> np.ndarray:
    out = []
    k = 1
    while len(out) < n:
        out.extend(int(c) for c in bin(k)[2:])
        k += 1
    return np.array(out[:n], dtype=np.int64)


def cf_interval(num_lo: int, num_hi: int, den: int, kmax: int) -> list:
    """rigorous common-prefix CF of the interval
    [num_lo/den, num_hi/den] by interval Euclid: a term is emitted
    only when both endpoints agree on floor; the interval reverses
    under x -> 1/(x - a)."""
    out = []
    lo_n, lo_d = num_lo, den
    hi_n, hi_d = num_hi, den
    while len(out) < kmax:
        if lo_d == 0 or hi_d == 0:
            break
        qlo, rlo = divmod(lo_n, lo_d)
        qhi, rhi = divmod(hi_n, hi_d)
        if qlo != qhi:
            break
        out.append(int(qlo))
        # x -> 1/(x - a): [lo, hi] -> [1/(hi - a), 1/(lo - a)]
        lo_n, lo_d, hi_n, hi_d = hi_d, rhi, lo_d, rlo
    return out


def gen_cf(tag: str, kmax: int) -> list:
    """CF partial quotients a_1.. (a_0 dropped).  pi/e: interval
    Euclid at CF_DPS digits (rigorous prefix); sqrt2/phi: exact
    periodic forms (disclosed)."""
    if tag == "sqrt2":
        return [2] * kmax
    if tag == "phi":
        return [1] * kmax
    with mp.workdps(CF_DPS + 20):
        x = {"pi": mp.pi, "e": mp.e}[tag]
        den = 10 ** CF_DPS
        plo = int(mp.floor(x * den))
    cf = cf_interval(plo, plo + 1, den, kmax + 1)
    return cf[1:]                                 # drop a_0


def gen_cf_rand(seed: int, kmax: int) -> list:
    """Gauss-Kuzmin-distributed quotients: u uniform(0,1),
    x = 2^u - 1 (Gauss-measure inverse CDF), a = floor(1/x)."""
    rng = np.random.default_rng(seed)
    u = rng.random(kmax)
    x = np.exp2(u) - 1.0
    return [max(1, int(1.0 / xv)) for xv in x]


def gen_dig_rand(seed: int, n: int) -> np.ndarray:
    rng = np.random.default_rng(seed)
    return rng.integers(0, 10, n).astype(np.int64)


def cf_logq(quots: list) -> list:
    """ln q_k of the convergent denominators (exact ints)."""
    qm1, q = 0, 1
    out = []
    for a in quots:
        qm1, q = q, a * q + qm1
        out.append(math.log(q))
    return out


# ======================================================== comb layer
def mangoldt_atoms_f(hi: int) -> list:
    """(log q, Lambda(p)/sqrt q) float prime-power atoms, q <= hi."""
    comp = np.zeros(hi + 1, dtype=bool)
    out = []
    for p in range(2, hi + 1):
        if comp[p]:
            continue
        comp[p * p:: p] = True
        q = p
        while q <= hi:
            out.append((math.log(q), math.log(p) / math.sqrt(q)))
            q *= p
    out.sort()
    return out


def w1_main(h: int) -> float:
    return sum(w for _u, w in mangoldt_atoms_f(int(math.floor(h))))


def stream_values(world: str, half: str) -> np.ndarray:
    """the centered stream v_1..v_STREAM_LEN for a dense-grid world;
    half A = values 1.., half B = values HALF_B_OFF+1.."""
    n = STREAM_LEN + HALF_B_OFF
    fam, tag = world.split(":", 1)
    if fam == "DIG10":
        if tag == "champ":
            d = gen_champ_digits(n)
        elif tag.startswith("rand"):
            d = gen_dig_rand(int(tag[4:]), n)
        else:
            d = DIGITS10[tag][:n]
        v = d.astype(float) - 4.5
    elif fam == "DIG2":
        if tag == "champ":
            b = gen_champ_bits(n)
        elif tag.startswith("rand"):
            b = gen_dig_rand(int(tag[4:]), n) % 2
        else:
            b = BITS2[tag][:n]
        v = 2.0 * b.astype(float) - 1.0
    elif fam == "CF":
        if tag == "liouv":
            # a_j = 10^j handled in log space (overflow-safe)
            v = (np.arange(1, n + 1, dtype=float) * math.log(10.0)
                 - math.log(K0))
        else:
            if tag.startswith("rand"):
                a = gen_cf_rand(int(tag[4:]), n)
            else:
                a = CFS[tag][:n]
            v = np.log(np.array(a, dtype=float)) - math.log(K0)
    else:
        raise ValueError(world)
    off = 0 if half == "A" else HALF_B_OFF
    return v[off: off + STREAM_LEN]


def comb_for(world: str, h: int, half: str) -> list:
    """the frozen world -> comb map at rung h; returns float atoms
    [(u, w)] already L1-rescaled to W1_MAIN(h)."""
    aa = math.log(h) / 2.0
    L2v = 2.0 * aa
    W1 = w1_main(h)
    N = NATOMS[h]
    if world == "MANGOLDT":
        # exact prime-power atoms as ("PP", q, p) markers -> mp-exact
        # (log q, log p/sqrt q) inside assemble_mprime, byte-matching
        # the build_cell recipe (port gate at 1e-25)
        hi = int(math.floor(h))
        comp = np.zeros(hi + 1, dtype=bool)
        nlist = []
        for p in range(2, hi + 1):
            if comp[p]:
                continue
            comp[p * p:: p] = True
            q = p
            while q <= hi:
                nlist.append((q, p))
                q *= p
        nlist.sort()
        return [("PP", q, p) for q, p in nlist]
    if world == "P-BBP":
        cmap = {1: 4.0, 4: -2.0, 5: -1.0, 6: -1.0}
        atoms = []
        k = 0
        while 8 * k + 1 <= h:
            for j, cj in cmap.items():
                nn = 8 * k + j
                if 2 <= nn <= h:
                    atoms.append((math.log(nn),
                                  cj * 16.0 ** (-k) / math.sqrt(nn)))
            k += 1
        s1 = sum(abs(w) for _u, w in atoms)
        return [(u, w * W1 / s1) for u, w in atoms]
    if world.startswith("CFGEOM:"):
        tag = world.split(":", 1)[1]
        if tag.startswith("rand"):
            quots = gen_cf_rand(int(tag[4:]),
                                STREAM_LEN + HALF_B_OFF)
        else:
            quots = CFS[tag][:STREAM_LEN + HALF_B_OFF]
        off = 0 if half == "A" else HALF_B_OFF
        sub = quots[off: off + N + 1]
        lq = cf_logq(sub)
        top = lq[N]
        atoms = [(L2v * lq[k] / top, 1.0) for k in range(N)]
        s1 = float(N)
        return [(u, w * W1 / s1) for u, w in atoms]
    # dense-grid stream worlds
    v = stream_values(world, half)[:N]
    s1 = float(np.sum(np.abs(v)))
    atoms = [((j + 1) * L2v / (N + 1), float(v[j]) * W1 / s1)
             for j in range(N)]
    return atoms


# ===================================================== wall/gram layer
def rung_shared(h: int, dps: int) -> dict:
    """per-rung shared build: build_cell(MAIN) once (geometry blocks
    + MANGOLDT reference wall), the world-blind Gram at the CTRL_NZ
    ward window, and its eigen-decomposition at padded dps."""
    gam = ward_cache()
    ce = R4.build_cell(h, KFAC, "MAIN", dps, want_mp=True)
    K = ce["K"]
    ndig = min(dps - 2, NDIG_CAP)
    out = dict(h=h, dps=dps, K=K, ndig=ndig,
               cn_main=list(ce["cn_mp_str"]))
    with mp.workdps(dps):
        aa = mp.log(h) / 2
        b = [(kk * mp.pi / aa) ** 2 for kk in range(K)]
        Tlo = 2 * math.pi * h + Z_OVERHANG
        Gm = [[mp.mpf(0)] * K for _ in range(K)]
        Smu = mp.mpf(0)
        nz_used = 0
        for g in gam[:CTRL_NZ]:
            gf = float(g)
            if gf <= Tlo:
                continue
            gm = mp.mpf(repr(gf))
            g2 = gm * gm
            s = mp.sin(aa * gm)
            mu = s * s / g2
            Smu += mu
            psi = [g2 / (g2 - b[kk]) if kk else mp.mpf(1)
                   for kk in range(K)]
            for kk in range(K):
                pk = mu * psi[kk]
                row = Gm[kk]
                for ll in range(kk + 1):
                    row[ll] += pk * psi[ll]
            nz_used += 1
        for kk in range(K):
            for ll in range(kk):
                Gm[ll][kk] = Gm[kk][ll]
        Dg = [mp.sqrt(Gm[kk][kk]) for kk in range(K)]
        out["nz_used"] = nz_used
        out["dg_str"] = [mp.nstr(Dg[kk], ndig) for kk in range(K)]
        out["smu_str"] = mp.nstr(Smu, ndig)
        out["gn_str"] = [[mp.nstr(Gm[i][j] / (Dg[i] * Dg[j]), ndig)
                          for j in range(K)] for i in range(K)]
        Mgeo = ce["mpPole"] + ce["mpArch"]
        out["mgeo_str"] = [[mp.nstr(Mgeo[i, j], ndig)
                            for j in range(K)] for i in range(K)]
        out["mprime_main_str"] = [[mp.nstr(ce["mpPrime"][i, j], ndig)
                                   for j in range(K)] for i in range(K)]
    dpse = ndig + EIG_PAD
    with mp.workdps(dpse):
        Gn = mp.matrix(K, K)
        for i in range(K):
            for j in range(K):
                Gn[i, j] = mp.mpf(out["gn_str"][i][j])
        Ev, Q = mp.eigsy(Gn)
        out["lam_str"] = [mp.nstr(Ev[i], dpse - 5) for i in range(K)]
        out["q_str"] = [[mp.nstr(Q[i, j], dpse - 5) for j in range(K)]
                        for i in range(K)]
        out["gmin"] = float(min(Ev[i] for i in range(K)))
    return out


def assemble_mprime(h: int, dps: int, K: int, atoms_f: list):
    """even-sector Mprime from float atoms -- R4.build_cell recipe
    ported VERBATIM (pj off-diagonal + psi_d diagonal + nrm
    normalization); port-gated on the MANGOLDT world."""
    with mp.workdps(dps):
        aa = mp.log(h) / 2
        L2v = 2 * aa
        oms = [kk * mp.pi / aa for kk in range(K)]
        par = [mp.mpf((-1.0) ** kk) for kk in range(K)]
        dsig = mp.mpf(-1)
        atoms = [(mp.log(a[1]), mp.log(a[2]) / mp.sqrt(a[1]))
                 if (isinstance(a, tuple) and len(a) == 3
                     and a[0] == "PP")
                 else (mp.mpf(repr(a[0])), mp.mpf(repr(a[1])))
                 for a in atoms_f]
        pj = [sum((w * mp.sin(o * u) for u, w in atoms), mp.mpf(0))
              for o in oms]
        Mp = mp.zeros(K, K)
        for i in range(K):
            for j2 in range(i):
                sg = par[i] * par[j2]
                den = oms[j2] ** 2 - oms[i] ** 2
                od = 2 * sg * (oms[i] * pj[i] - oms[j2] * pj[j2]) / den
                Mp[i, j2] += od
                Mp[j2, i] += od
        for i in range(K):
            o = oms[i]
            if i == 0:
                pdiag = sum((w * (L2v - u) for u, w in atoms), mp.mpf(0))
            else:
                pdiag = sum((w * ((aa - u / 2) * mp.cos(o * u)
                                  + dsig * mp.sin(o * u) / (2 * o))
                             for u, w in atoms), mp.mpf(0))
            Mp[i, i] += 2 * pdiag
        nrm = [mp.sqrt(L2v) if kk == 0 else mp.sqrt(aa)
               for kk in range(K)]
        for i in range(K):
            for j2 in range(K):
                Mp[i, j2] = Mp[i, j2] / (nrm[i] * nrm[j2])
        for i in range(K):
            for j2 in range(i):
                sym = (Mp[i, j2] + Mp[j2, i]) / 2
                Mp[i, j2] = sym
                Mp[j2, i] = sym
        return Mp


def world_jet(sh: dict, atoms_f: list) -> dict:
    """wall -> source -> jet for one world at one rung: M = Mgeo -
    Mprime(world), lowest eigenvector, sign fix, cn = v/nrm,
    d = (-1)^k c, A0, Jn."""
    h, dps, K, ndig = sh["h"], sh["dps"], sh["K"], sh["ndig"]
    Mp = assemble_mprime(h, dps, K, atoms_f)
    with mp.workdps(dps):
        aa = mp.log(h) / 2
        L2v = 2 * aa
        M = mp.matrix(K, K)
        for i in range(K):
            for j in range(K):
                M[i, j] = mp.mpf(sh["mgeo_str"][i][j]) - Mp[i, j]
        E, V = mp.eigsy(M)
        i0 = min(range(K), key=lambda i: E[i])
        nrm = [mp.sqrt(L2v) if kk == 0 else mp.sqrt(aa)
               for kk in range(K)]
        cn = [V[kk, i0] / nrm[kk] for kk in range(K)]
        imax = max(range(K), key=lambda kk: abs(cn[kk]))
        if cn[imax] < 0:
            cn = [-v for v in cn]
        d = [((-1) ** kk) * cn[kk] for kk in range(K)]
        A0 = sum(d)
        if abs(A0) < mp.mpf(repr(A0_GUARD)):
            return dict(error="A0-guard", h=h)
        Dg = [mp.mpf(s) for s in sh["dg_str"]]
        sq = mp.sqrt(mp.mpf(sh["smu_str"]))
        Jn = [(d[kk] / A0) * Dg[kk] / sq for kk in range(K)]
        return dict(h=h, K=K, ndig=ndig,
                    cn_str=[mp.nstr(v, ndig) for v in cn],
                    jn_str=[mp.nstr(v, ndig) for v in Jn])


def mass_location(sh: dict, jn_str: list) -> dict:
    """the D1 observables from the shared eigen-decomposition:
    log10tail at the primary cut, topshare, mu_m, mass ward."""
    K, ndig = sh["K"], sh["ndig"]
    dpse = ndig + EIG_PAD
    with mp.workdps(dpse):
        l10 = mp.log(10)
        lams = [mp.mpf(s) for s in sh["lam_str"]]
        Jn = [mp.mpf(s) for s in jn_str]
        svals = []
        for i in range(K):
            acc = mp.mpf(0)
            for kk in range(K):
                acc += mp.mpf(sh["q_str"][kk][i]) * Jn[kk]
            svals.append(acc)
        tot = mp.mpf(0)
        for i in range(K):
            tot += lams[i] * svals[i] * svals[i]
        # ward: direct quadratic form vs eigen-sum
        quad = mp.mpf(0)
        for i in range(K):
            gi = [mp.mpf(sh["gn_str"][i][j]) for j in range(K)]
            acc = mp.mpf(0)
            for j in range(K):
                acc += gi[j] * Jn[j]
            quad += Jn[i] * acc
        ward = float(abs(tot / quad - 1))
        lmax = max(lams)
        itop = max(range(K), key=lambda i: lams[i])
        cut = mp.mpf(CUT_PRIMARY) * lmax
        sub = mp.mpf(0)
        for i in range(K):
            if lams[i] >= cut:
                sub += lams[i] * svals[i] * svals[i]
        tail = abs(mp.mpf(1) - sub / tot)
        topshare = float(lams[itop] * svals[itop] ** 2 / tot)
        mu_m = mp.mpf(0)
        mpos = mp.mpf(0)
        for i in range(K):
            if lams[i] <= 0:
                continue
            mi = lams[i] * svals[i] * svals[i]
            if mi > 0:
                mu_m += mi * mp.log(lams[i] / lmax) / l10
                mpos += mi
        mu_mf = float(mu_m / mpos) if mpos > 0 else float("nan")
        return dict(log10tail=float(mp.log(tail + mp.mpf("1e-300"))
                                    / l10),
                    topshare=topshare, mu_m=mu_mf, ward=ward)


